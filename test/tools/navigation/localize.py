"""Read-only live/replay LiDAR localization and browser map. No motion APIs."""
import argparse
import fcntl
import json
import math
import os
from pathlib import Path
import socket
import subprocess
import sys
import tempfile
import time

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0,str(REPO))


def run(args):
    import numpy as np
    from GuideBot.navigation.localization import MapTracker, decode_cloud
    from test.tools.navigation.localization_runtime import SensorInbox
    from test.tools.navigation.localization_web import start
    from GuideBot.navigation.mapping.offline_mapping import write_png
    from runtime.app.environment import sdk_environment
    from GuideBot.robot.sensors.runtime import source_types
    from test.tools.navigation.lab import stop

    base=Path.home()/'.local/state/guidebot/navigation'
    base.mkdir(parents=True,exist_ok=True)
    with (base/'capture.lock').open('a') as lease:
        try:
            fcntl.flock(lease,fcntl.LOCK_EX|fcntl.LOCK_NB)
        except BlockingIOError:
            raise RuntimeError('Another sensor capture/localization is running') from None
        tracker=MapTracker.load(args.map_directory,(args.initial_x,args.initial_y,math.radians(args.initial_yaw_deg)))
        info=json.loads((args.map_directory/'report.json').read_text())['grid']
        # This map format is generated by our offline mapper; no arbitrary YAML image path.
        raw=(args.map_directory/'map.pgm').read_bytes().split(b'\n',3)
        if len(raw)!=4 or raw[0]!=b'P5' or raw[2]!=b'255' or raw[1]!=('%d %d'%(info['width'],info['height'])).encode():
            raise ValueError('Unexpected offline PGM layout')
        image=np.frombuffer(raw[3],dtype='uint8').reshape(info['height'],info['width'])
        if args.mode=='live':
            print('请放在采图起点附近并保持采图初始朝向；本工具仅定位，不控制机器人。',flush=True)
            try:
                input('按 Enter 开始实时雷达定位，Ctrl+C 结束：')
            except EOFError:
                raise RuntimeError('Interactive Enter required for live localization') from None
        directory=Path(tempfile.mkdtemp(prefix='localization-',dir=base))
        directory.chmod(0o700)
        write_png(directory/'map.png',np.repeat(image[:,:,None],3,axis=2))
        socket_root=Path(tempfile.mkdtemp(prefix='gb-loc-'))
        socket_root.chmod(0o700)
        endpoint=socket_root/'source.sock'
        listener=socket.socket(socket.AF_UNIX,socket.SOCK_STREAM)
        source=connection=inbox=web=web_thread=None
        failed=None
        timings=[]
        log=(directory/'source.log').open('w')
        events=(directory/'localization.jsonl').open('w')
        statistics={}
        try:
            listener.bind(str(endpoint));listener.listen(1);listener.settimeout(10)
            command=[sys.executable,str(REPO/'test/tools/navigation/lab.py'),
                     'source' if args.mode=='live' else 'replay-source',
                     '--directory',str(directory),'--endpoint',str(endpoint),'--interface',args.interface]
            if args.mode=='replay':command+=['--capture',str(args.capture)]
            if args.duration is not None:command+=['--duration',str(args.duration)]
            source=subprocess.Popen(command,cwd=REPO,env=sdk_environment(),stdout=log,stderr=subprocess.STDOUT,start_new_session=True)
            connection,_=listener.accept()
            inbox=SensorInbox(connection,source_types());inbox.thread.start()
            def status():
                result=tracker.snapshot()
                result.update(inbox.statistics())
                if inbox.done:
                    result.update(valid=False,state='stopped',reason='传感器连接已结束')
                return result
            web,web_thread=start((directory/'map.png').read_bytes(),info,status,args.web_port)
            print('定位日志：'+str(directory),flush=True)
            print('地图显示：http://127.0.0.1:'+str(web.server_port),flush=True)
            begun=time.monotonic();last_print=0.;last_input=begun
            while True:
                item=inbox.take()
                if item is not None:
                    payload,arrived=item;last_input=time.monotonic()
                    try:
                        msg=inbox.types['cloud'][1].deserialize(payload)
                        stamp=msg.header.stamp.sec+msg.header.stamp.nanosec/1e9
                        yaw=inbox.yaw_at(stamp)
                        tracker.update(decode_cloud(msg),stamp,yaw,arrived)
                    except (ValueError,np.linalg.LinAlgError) as error:
                        tracker.reject(str(error))
                    current=tracker.snapshot()
                    if current['valid']:timings.append(current['receive_to_result_ms'])
                    event={k:v for k,v in current.items() if k!='trajectory'}
                    events.write(json.dumps(event,ensure_ascii=False,allow_nan=False)+'\n');events.flush()
                    path=directory/'status.tmp'
                    path.write_text(json.dumps(event,ensure_ascii=False,allow_nan=False))
                    path.replace(directory/'status.json')
                    # Limit compute rate; reader thread continues draining DDS IPC.
                    if args.rate_hz:
                        time.sleep(max(0.,1/args.rate_hz-(time.monotonic()-last_input)))
                else:
                    if inbox.done:break
                    if time.monotonic()-last_input>5:
                        raise RuntimeError('No fresh LiDAR clouds for 5 seconds')
                    time.sleep(.01)
                now=time.monotonic()
                if now-last_print>3:
                    s=status();print('%s accepted=%d rejected=%d age=%.2fs %s'%(s['state'],s['accepted'],s['rejected'],s['age_s'],s['reason']),flush=True);last_print=now
                if inbox.error:raise RuntimeError(inbox.error)
            source.wait(timeout=5)
            if source.returncode:raise RuntimeError('Sensor source failed; see source.log')
            if inbox.error:raise RuntimeError(inbox.error)
            if tracker.state['accepted']==0:raise RuntimeError('No valid localization; inspect localization.jsonl')
        except KeyboardInterrupt:
            pass
        except Exception as error:
            failed=type(error).__name__+': '+str(error)
        finally:
            stop(source)
            if inbox:
                inbox.stop_event.set()
                statistics=inbox.statistics()
            if connection:
                try:connection.shutdown(socket.SHUT_RDWR)
                except OSError:pass
                connection.close()
            listener.close()
            if inbox:inbox.thread.join(timeout=3)
            if web:
                web.shutdown();web.server_close();web_thread.join(timeout=2)
            log.close();events.close()
            if endpoint.exists():endpoint.unlink()
            socket_root.rmdir()
            result=dict(directory=str(directory),map_directory=str(args.map_directory),mode=args.mode,
                        error=failed,motion_commands=False,audio_started=False,
                        accepted=tracker.state['accepted'],rejected=tracker.state['rejected'],
                        receive_to_result_median_ms=float(np.median(timings)) if timings else None,
                        receive_to_result_p95_ms=float(np.percentile(timings,95)) if timings else None,
                        **statistics)
            (directory/'result.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
            print(json.dumps(result,ensure_ascii=False,indent=2),flush=True)
        return int(failed is not None)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode',choices=['live','replay'])
    parser.add_argument('--map-directory',required=True,type=Path)
    parser.add_argument('--capture',type=Path)
    parser.add_argument('--initial-x',type=float,default=0.)
    parser.add_argument('--initial-y',type=float,default=0.)
    parser.add_argument('--initial-yaw-deg',type=float,default=0.)
    parser.add_argument('--interface',default='eth0')
    parser.add_argument('--duration',type=float)
    parser.add_argument('--rate-hz',type=float,default=3.)
    parser.add_argument('--web-port',type=int,default=8765)
    parser.add_argument('--worker',action='store_true',help=argparse.SUPPRESS)
    args=parser.parse_args()
    args.map_directory=args.map_directory.expanduser().resolve()
    for name in ['report.json','map.pgm']:
        if not (args.map_directory/name).is_file():parser.error('Missing map file: '+name)
    if not any((args.map_directory/name).is_file() for name in ['mapping.npz','matched3d.npz']):
        parser.error('Map directory has no matched 3D points')
    if not all(math.isfinite(x) for x in [args.initial_x,args.initial_y,args.initial_yaw_deg,args.rate_hz]):
        parser.error('Initial pose and rate must be finite')
    if not .1<=args.rate_hz<=10:parser.error('rate-hz must be 0.1..10')
    if args.duration is not None and not 0<args.duration<=86400:parser.error('duration must be 0..86400')
    if not 0<=args.web_port<=65535:parser.error('invalid web port')
    if args.mode=='replay':
        if args.capture is None:parser.error('replay requires --capture')
        args.capture=args.capture.expanduser().resolve()
        for name in ['samples.cdr','samples.jsonl']:
            if not (args.capture/name).is_file():parser.error('Missing capture file: '+name)
    if not args.worker:
        from runtime.app.environment import sdk_environment
        env=sdk_environment();env['OPENBLAS_NUM_THREADS']='1'
        return subprocess.call([sys.executable,str(Path(__file__).resolve()),*sys.argv[1:],'--worker'],env=env,cwd=REPO)
    return run(args)


if __name__=='__main__':
    raise SystemExit(main())
